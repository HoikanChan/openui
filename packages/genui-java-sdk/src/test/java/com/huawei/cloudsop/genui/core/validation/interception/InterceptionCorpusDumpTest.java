/**
 * Acceptance artifact generator (design Decision 11.5): dumps every corpus case as DSL → full
 * validator issues → the incremental repair prompt the repair model would actually see (post
 * cascade suppression). Reviewing {@code target/interception-corpus-dump.md} after any hint/prompt
 * change is the fastest way to judge repair-friendliness case by case. The output is a build
 * artifact — never commit it.
 *
 * @since 2026
 */
class InterceptionCorpusDumpTest {

    private static final Path OUTPUT = Path.of("target", "interception-corpus-dump.md");

    @Test
    void dumpCorpusPromptView() throws IOException, LlmTransportException {
        StringBuilder md = new StringBuilder();
        md.append("# Interception corpus — prompt view dump\n\n");
        md.append("Generated by `InterceptionCorpusDumpTest`; build artifact, do not commit.\n");
        md.append(
                "Issues show the FULL validator output; the prompt sections show what survives\n");
        md.append("cascade suppression in `RepairPromptBuilder`.\n");

        for (Map<String, Object> testCase : InterceptionCorpusTest.cases()) {
            String id = InterceptionCorpusTest.str(testCase.get("id"));
            String dsl =
                    InterceptionCorpusTest.read(
                            "interception-corpus/"
                                    + InterceptionCorpusTest.str(testCase.get("dslFile")));
            GenerationContract contract =
                    InterceptionCorpusTest.loadContract(
                            InterceptionCorpusTest.str(testCase.get("contractFile")));
            ValidationResult result = InterceptionCorpusTest.validate(testCase);

            md.append("\n---\n\n## ").append(id);
            md.append(" (")
                    .append(InterceptionCorpusTest.str(testCase.get("expectedClass")))
                    .append(", ");
            md.append(InterceptionCorpusTest.str(testCase.get("expectedOutcome"))).append(")\n");
            md.append("\n### DSL\n\n```\n").append(dsl.strip()).append("\n```\n");

            md.append("\n### Validator issues (full)\n\n");
            if (result.issues().isEmpty()) {
                md.append("(none)\n");
            } else {
                for (ValidationIssue issue : result.issues()) {
                    md.append("- ")
                            .append(issue.severity())
                            .append(" [")
                            .append(issue.code())
                            .append("] ")
                            .append(issue.message())
                            .append(" stmt=")
                            .append(issue.statementId())
                            .append(" line=")
                            .append(issue.line())
                            .append(':')
                            .append(issue.column());
                    if (issue.hint() != null) {
                        md.append("\n  hint: ").append(issue.hint());
                    }
                    md.append('\n');
                }
            }

            List<ChatMessage> messages = repairMessages(dsl, contract, result);
            if (messages.isEmpty()) {
                md.append("\nNo repair requested: the validator accepts this program.\n");
                continue;
            }
            md.append("\n### Incremental repair prompt — system (post-suppression)\n\n```\n")
                    .append(messages.get(0).content().strip())
                    .append("\n```\n");
            md.append("\n### Incremental repair prompt — user\n\n```\n")
                    .append(messages.get(1).content().strip())
                    .append("\n```\n");
        }

        Files.createDirectories(OUTPUT.getParent());
        Files.writeString(OUTPUT, md.toString(), StandardCharsets.UTF_8);
        assertTrue(Files.size(OUTPUT) > 0, "dump artifact written to " + OUTPUT);
    }

    /** Capture the real repair request through the module interface, using corpus diagnostics. */
    private static List<ChatMessage> repairMessages(
            String dsl, GenerationContract contract, ValidationResult result)
            throws LlmTransportException {
        List<String> bodies = new ArrayList<>();
        LlmTransport transport =
                new LlmTransport() {
                    @Override
                    public String post(String body) {
                        throw new AssertionError("Only streaming requests are expected");
                    }

                    @Override
                    public InputStream postStream(String body) {
                        bodies.add(body);
                        String content = bodies.size() == 1 ? dsl : "";
                        String frame =
                                SseFrames.of(
                                        Json.stringify(
                                                Map.of(
                                                        "choices",
                                                        List.of(
                                                                Map.of(
                                                                        "delta",
                                                                        Map.of(
                                                                                "content",
                                                                                content))))));
                        return new ByteArrayInputStream(
                                (frame + SseFrames.done()).getBytes(StandardCharsets.UTF_8));
                    }
                };
        RepairLoop session =
                new RepairLoop(
                        new RepairLoop.Context(null, null, contract, Map.of(), 1),
                        request -> result,
                        GenUiLlmConfig.defaults(),
                        transport,
                        () -> false,
                        delta -> {});
        session.run("{}");
        if (bodies.size() == 1) {
            return List.of();
        }
        Map<String, Object> body = Json.asObject(Json.parse(bodies.get(1)), "repair request");
        return Json.asList(body.get("messages"), "messages").stream()
                .map(value -> Json.asObject(value, "message"))
                .map(
                        message ->
                                new ChatMessage(
                                        String.valueOf(message.get("role")),
                                        String.valueOf(message.get("content"))))
                .toList();
    }
}
